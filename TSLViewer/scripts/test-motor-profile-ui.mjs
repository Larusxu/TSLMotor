// Unit tests of actual UI codec, using the real hardware archive evidence.
// Does not open a port, run browser mocks, or enable a motor.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const transpile=s=>ts.transpileModule(s,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const url=s=>`data:text/javascript;base64,${Buffer.from(s).toString('base64')}`;
const units=url(transpile(fs.readFileSync(new URL('../src/lib/units.ts',import.meta.url),'utf8')));
const src=fs.readFileSync(new URL('../src/lib/motor-profile-ui.ts',import.meta.url),'utf8').replace(/^import .*;\r?\n/gm,'');
const m=await import(url(`const {composePidConfig,parsePidConfig}=await import('${units}');\n`+transpile(src)));
const path=process.argv[2]??'D:/WorkeSpace/work/comp_proj/TeslaHand/build/rebuild/coordinate-partition-can/responses.json';
const records=JSON.parse(fs.readFileSync(path,'utf8'));
const base=records.find(r=>r.storage?.motor===9&&r.storage.data?.length===128)?.storage.data;
assert(base,'Real M9 MTR1 evidence is required');
m.checkedProfile(base,9);
const p=m.pidFromProfile(base), round=m.profileWithPid(base,p,9);
assert.deepEqual(round,base,'Unchanged profile roundtrip must be byte exact');
const changed=m.profileWithPid(base,{...p,torque_p:65,torque_limit_ma:450},9);
assert.equal(m.word(changed,36)>>>16,65);
assert.equal(m.word(changed,48)&65535,m.word(base,48)&65535,'Iq edit preserves Id');
for(const [a,b] of [[0,28],[40,48],[60,120]])assert.deepEqual(changed.slice(a,b),base.slice(a,b));
assert.equal(m.word(changed,120),m.crc32(changed.slice(0,120)));
assert.throws(()=>m.checkedProfile(base,8));
const broken=[...base];broken[20]^=1;assert.throws(()=>m.checkedProfile(broken,9));
const transition=m.profileWithPid(base,{...p,overwrite_target:true,keep_pos_target:true},9);
assert.equal(m.word(transition,28)&3,3);
assert.equal(m.pidFromProfile(transition).keep_pos_target,true);
assert.throws(()=>m.profileWithPid(base,{...p,torque_limit_ma:1200},9));
assert.throws(()=>m.profileWithPid(base,{...p,vel_limit_rpm:NaN},9));
console.log('PASS real MTR1 codec: exact roundtrip, preserved identity/offset/Id/hash/reserved, CRC, invalid inputs and transition bits');

const task={max_rpm:500,mode:"position_ramp",planning:"limits",accel_deg_s2:6000,decel_deg_s2:12000,trip_ma:600,over_ms:180,sample_ms:60,comm_timeout_ms:1000,fault_action:"disable"};
const configured=m.profileWithRun(base,p,task,9);
assert.equal(m.word(configured,68),m.RUN_TAG);
assert.deepEqual(configured.slice(12,68),base.slice(12,68),'RUN1 never changes PI/identity/offset/unique limits');
assert.equal(m.word(configured,104),1);assert.equal(m.word(configured,108),2);
const recovered=m.runFromProfile(configured,task);
assert.equal(recovered.max_rpm,p.vel_limit_rpm);assert.equal(recovered.limit_ma,p.torque_limit_ma);
assert(Math.abs(recovered.accel_deg_s2-6000)<10);
assert(Math.abs(recovered.decel_deg_s2-12000)<10);
assert.equal(m.word(configured,120),m.crc32(configured.slice(0,120)));
assert.throws(()=>m.profileWithRun(base,p,{...task,over_ms:30},9));
assert.throws(()=>m.profileWithRun(base,p,{...task,comm_timeout_ms:100},9));
assert.doesNotThrow(()=>m.profileWithRun(base,p,{...task,mode:'velocity_ramp'},9));
console.log('PASS RUN1: one current/velocity ceiling, PI/Id/offset binding preserved, acceleration conversion, constraints, CRC and mode defaults');

const piOnly=m.profileWithPiOnly(configured,{...p,torque_p:66,torque_limit_ma:900,vel_limit_rpm:1234},9);
assert.equal(m.word(piOnly,36)>>>16,66);
assert.deepEqual(piOnly.slice(48,120),configured.slice(48,120),'PI commit preserves saved limits/RUN1');
const controlOnly=m.profileWithControlOnly(configured,{...p,torque_p:99,torque_limit_ma:450,flux_limit_ma:100,uq_ud_limit:12000},task,9);
assert.equal(m.word(controlOnly,36)>>>16,99,'Control commit uses current PID page PI rather than stale W25');
assert.equal(m.word(controlOnly,48),m.word(configured,48),'Left commit ignores unapplied Iq/Id');
assert.equal(m.word(controlOnly,56),m.word(configured,56),'Left commit ignores unapplied voltage');
const maximum=m.profileWithPid(base,{...p,torque_limit_ma:1050},9);
assert((m.word(maximum,48)>>>16)*m.MA_PER_RAW<=1050,'Quantization never exceeds safety ceiling');
assert.equal(m.runFromProfile(configured,{...task,planning:'time'}).planning,'limits');
console.log('PASS independent PI/control commits, conservative current quantization and saved native Ramp planning');

