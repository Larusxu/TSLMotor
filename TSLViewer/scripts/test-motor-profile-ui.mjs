assert.doesNotThrow(()=>m.profileWithControlOnly(configured,{...edited,torque_limit_ma:NaN,uq_ud_limit:NaN},task,9),'Invalid unapplied right edits cannot block left apply');
assert.doesNotThrow(()=>m.profileWithLongTermOnly(configured,{...edited,vel_limit_rpm:NaN,torque_p:NaN},9),'Invalid unapplied left/PI edits cannot block right apply');
const leftRead=m.motionFromProfile(left,{...task,limit_ma:777});assert.equal(leftRead.limit_ma,777);assert.equal(leftRead.max_rpm,m.word(left,112)/m.COUNTS_PER_RPM);
