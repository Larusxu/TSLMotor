"""Generate ``tslviewer/core/registers.py`` from the TSLViewer TypeScript sources.

The PyQt port keeps a single source of truth for the 189-entry TMC6460 register
map: the generated table in ``TSLViewer/src/lib/registers.gen.ts`` plus the
hand written metadata in ``registers.ts``.  Re-run this script whenever those
files change.

    python scripts/gen_registers.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "TSLViewer" / "src" / "lib"
OUT = HERE.parent / "tslviewer" / "core" / "registers.py"


def parse_registers(text: str) -> list[tuple[int, str, str]]:
    rows = re.findall(
        r'\{\s*addr:\s*0x([0-9A-Fa-f]+),\s*name:\s*"([^"]+)",\s*group:\s*"([^"]+)"\s*\}',
        text,
    )
    return [(int(addr, 16), name, group) for addr, name, group in rows]


def _matching_brace(text: str, start: int) -> int:
    depth = 0
    for i in range(start, len(text)):
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced braces")


def parse_meta(text: str) -> dict[int, dict]:
    head = text.index("export const REG_META")
    body_start = text.index("{", head)
    body_end = _matching_brace(text, body_start)
    body = text[body_start + 1 : body_end]

    meta: dict[int, dict] = {}
    pos = 0
    key_re = re.compile(r"0x([0-9A-Fa-f]+)\s*:\s*\{")
    while True:
        m = key_re.search(body, pos)
        if not m:
            break
        start = body.index("{", m.end() - 1)
        end = _matching_brace(body, start)
        chunk = body[start + 1 : end]
        addr = int(m.group(1), 16)
        entry: dict = {}
        label = re.search(r'label:\s*"([^"]*)"', chunk)
        desc = re.search(r'desc:\s*"([^"]*)"', chunk)
        if label:
            entry["label"] = label.group(1)
        if desc:
            entry["desc"] = desc.group(1)
        if re.search(r"\bro:\s*true", chunk):
            entry["ro"] = True
        bits: list[tuple[int, int, str]] = []
        bits_at = chunk.find("bits:")
        if bits_at >= 0:
            arr_start = chunk.index("[", bits_at)
            arr_end = _matching_brace_like(chunk, arr_start, "[", "]")
            segment = chunk[arr_start:arr_end]
            for lo, hi, name in re.findall(
                r'\[\s*(\d+)\s*,\s*(\d+)\s*,\s*"([^"]+)"\s*\]', segment
            ):
                bits.append((int(lo), int(hi), name))
        if bits:
            entry["bits"] = bits
        meta[addr] = entry
        pos = end + 1
    return meta


def _matching_brace_like(text: str, start: int, open_ch: str, close_ch: str) -> int:
    depth = 0
    for i in range(start, len(text)):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced brackets")


def parse_status_bits(text: str) -> list[tuple[int, str, str]]:
    block = text[text.index("export const STATUS_BITS") :]
    return [
        (int(bit), name, tone)
        for bit, name, tone in re.findall(
            r'\[\s*(\d+)\s*,\s*"([^"]+)"\s*,\s*"(info|warn|error)"\s*\]', block
        )
    ]


def parse_favorites(text: str) -> list[int]:
    block = text[text.index("export const FAVORITES") :]
    block = block[: block.index("]")]
    return [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", block)]


def parse_streamable(text: str) -> list[int]:
    block = text[text.index("export const STREAMABLE") :]
    block = block[: block.index("])")]
    return [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", block)]


def py_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    gen = (SRC / "registers.gen.ts").read_text(encoding="utf-8")
    regs = (SRC / "registers.ts").read_text(encoding="utf-8")

    registers = parse_registers(gen)
    meta = parse_meta(regs)
    status = parse_status_bits(regs)
    favorites = parse_favorites(regs)
    streamable = parse_streamable(regs)

    lines = [
        '"""TMC6460 register map – generated by scripts/gen_registers.py.',
        "",
        "Source: TSLViewer/src/lib/registers.gen.ts + registers.ts.",
        "Do not edit by hand; re-run the generator instead.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "",
        "",
        "@dataclass(frozen=True)",
        "class RegisterDef:",
        "    addr: int",
        "    name: str",
        "    group: str",
        "",
        "",
        "@dataclass",
        "class RegMeta:",
        "    label: str",
        '    desc: str = ""',
        "    bits: list[tuple[int, int, str]] = field(default_factory=list)",
        "    ro: bool = False",
        "",
        "",
        "GROUP_LABELS = {",
    ]
    groups = []
    for _, _, group in registers:
        if group not in groups:
            groups.append(group)
    group_labels = dict(
        re.findall(r'(\w+):\s*"([^"]+)"', regs[regs.index("GROUP_LABELS") : regs.index("};", regs.index("GROUP_LABELS"))])
    )
    for group in groups:
        lines.append(f"    {py_str(group)}: {py_str(group_labels.get(group, group))},")
    lines += ["}", "", "REGISTERS: list[RegisterDef] = ["]
    for addr, name, group in registers:
        lines.append(f"    RegisterDef(0x{addr:03X}, {py_str(name)}, {py_str(group)}),")
    lines += ["]", "", "REG_META: dict[int, RegMeta] = {"]
    for addr in sorted(meta):
        entry = meta[addr]
        bits = entry.get("bits", [])
        pieces = [f"label={py_str(entry.get('label', ''))}"]
        if entry.get("desc"):
            pieces.append(f"desc={py_str(entry['desc'])}")
        if bits:
            bits_src = ", ".join(f"({lo}, {hi}, {py_str(n)})" for lo, hi, n in bits)
            pieces.append(f"bits=[{bits_src}]")
        if entry.get("ro"):
            pieces.append("ro=True")
        lines.append(f"   0x{addr:03X}: RegMeta({', '.join(pieces)}),")
    lines += ["}", "", "FAVORITES: list[int] = ["]
    for i in range(0, len(favorites), 10):
        lines.append("    " + ", ".join(f"0x{v:03X}" for v in favorites[i : i + 10]) + ",")
    lines += ["]", "", "STREAMABLE: set[int] = {"]
    for i in range(0, len(streamable), 10):
        lines.append("    " + ", ".join(f"0x{v:03X}" for v in streamable[i : i + 10]) + ",")
    lines += ["}", "", "STATUS_BITS: list[tuple[int, str, str]] = ["]
    for bit, name, tone in status:
        lines.append(f"    ({bit}, {py_str(name)}, {py_str(tone)}),")
    lines += [
        "]",
        "",
        "",
        "def reg_by_addr(addr: int) -> RegisterDef | None:",
        "    for reg in REGISTERS:",
        "        if reg.addr == addr:",
        "            return reg",
        "    return None",
        "",
        "",
        "def reg_label(addr: int) -> str:",
        "    meta = REG_META.get(addr)",
        "    if meta:",
        "        return meta.label",
        "    reg = reg_by_addr(addr)",
        "    return reg.name if reg else f\"0x{addr:03X}\"",
        "",
        "",
        "def reg_name(addr: int) -> str:",
        "    reg = reg_by_addr(addr)",
        "    return reg.name if reg else \"—\"",
        "",
        "",
        "def group_of(addr: int) -> str:",
        "    reg = reg_by_addr(addr)",
        "    return reg.group if reg else \"UNKNOWN\"",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(registers)} registers, {len(meta)} metadata entries)")


if __name__ == "__main__":
    main()
